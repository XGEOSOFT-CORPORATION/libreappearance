"""Build the Aura GTK 3 themes (light + dark) used for LibreOffice's windows on Linux.

Each theme is Adwaita (built into GTK, always available) + the @aura_* colours
from design/tokens.json + the shared rules of src/gtk/aura.css.
"""
import argparse
from pathlib import Path

from tokens import ROOT, load_tokens

THEMES = {"light": "Aura", "dark": "Aura-dark"}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True, help="output themes directory")
    args = ap.parse_args()

    chrome = load_tokens()["chrome"]
    rules = (ROOT / "src" / "gtk" / "aura.css").read_text(encoding="utf-8")
    family, size = chrome["font"].rsplit(" ", 1)
    for variant, name in THEMES.items():
        spec = dict(chrome[variant])
        base = spec.pop("base")
        contained = "gtk-contained-dark.css" if base.endswith("-dark") else "gtk-contained.css"
        head = [f"/* Generated by tools/build_gtk.py — {name}. Do not edit. */",
                f'@import url("resource:///org/gtk/libgtk/theme/Adwaita/{contained}");', ""]
        head += [f"@define-color aura_{k} {v};" for k, v in spec.items()]
        head += ["", f'window, dialog, popover, menu, tooltip {{ font-family: "{family}", sans-serif; '
                     f"font-size: {size}pt; }}", ""]
        theme = Path(args.out) / name
        (theme / "gtk-3.0").mkdir(parents=True, exist_ok=True)
        (theme / "gtk-3.0" / "gtk.css").write_text("\n".join(head) + rules, encoding="utf-8")
        (theme / "index.theme").write_text(
            f"[Desktop Entry]\nType=X-GNOME-Metatheme\nName={name}\n"
            f"Comment=Aura theme for LibreOffice\nEncoding=UTF-8\n\n"
            f"[X-GNOME-Metatheme]\nGtkTheme={name}\n", encoding="utf-8")
        print(f"gtk[{variant}] -> {theme}")


if __name__ == "__main__":
    main()
